package lesson04_if_else;

public class Main4 {

  public static void main(String[] args) {

    int pontszam = 59;

    if (pontszam >= 90) {
      System.out.println("Jeles");
    } else if (pontszam >= 60) {
      System.out.println("Megfelelt");
    } else {
      System.out.println("Nem felelt meg");
    }

  }
}
