package lesson04_if_else;

public class Main3 {

  public static void main(String[] args) {

    int homerseklet = 20;

    if (homerseklet < 10) {
      System.out.println("Hideg van.");
    } else if (homerseklet < 20) {
      System.out.println("Kellemes idő van.");
    } else {
      System.out.println("Meleg van.");
    }

  }

}
