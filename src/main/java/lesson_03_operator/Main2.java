package lesson_03_operator;

public class Main2 {

  public static void main(String[] args) {

    int eletkor = 20;

    System.out.println(eletkor >= 18); // true
    System.out.println(eletkor < 18);  // false
    System.out.println(eletkor == 20); // true
    System.out.println(eletkor != 20); // false

  }

}
